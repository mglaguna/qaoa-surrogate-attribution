"""Regenerate the Energy Hub figures of the manuscript from energy_hub/data/.

Usage (from energy_hub/figures/scripts/):  python make_figures.py [NAME ...]

Each job runs in its own Python process, so that matplotlib settings made by one script
cannot affect another. Figures 4 and 10 are drawn after figure1_pipeline_schematic.py in the
same process, as in the original batch run (that script sets matplotlib style parameters on
which the two figures rely); this reproduces the published images exactly. Figures 3, 6 and 12 are drawn with a minimum text size of
8 pt (enlarge_fonts.py). Figure 1 (superstructure) is a draw.io diagram generated by
generate_energy_hub_superstructure.py and is not redrawn here.

  Manuscript figure   Job name        Script
  2                   fig2_schematic  figure1_pipeline_schematic.py
  3                   fig3            figure2_surrogate_landscapes.py              (8 pt)
  4                   fig4            figure3_sampling_concentration.py
  5                   fig5            figure4_candidate_flow.py
  6                   fig6            figure5_tac_vs_budget.py                     (8 pt)
  7, 11               fig7_fig11      generate_canonical_supplement_candidates.py  (FigureS1, FigureS2)
  8                   fig8            figS_attribution.py
  9                   fig9            figure6_landscape_context.py
  10                  fig10           figure7_engineering_fingerprints.py
  12                  fig12           generate_canonical_supplement_candidates.py  (FigureS3, 8 pt)
"""
import json
import subprocess
import sys

sys.path.insert(0, ".")

JOBS = {
    "fig2_schematic": ("figure1_pipeline_schematic", False),
    "fig3": ("figure2_surrogate_landscapes", True),
    "fig4": ("figure1_pipeline_schematic,figure3_sampling_concentration", False),
    "fig5": ("figure4_candidate_flow", False),
    "fig6": ("figure5_tac_vs_budget", True),
    "fig7_fig11": ("supplement_s1_s2", False),
    "fig8": ("figS_attribution", False),
    "fig9": ("figure6_landscape_context", False),
    "fig10": ("figure1_pipeline_schematic,figure7_engineering_fingerprints", False),
    "fig12": ("supplement_s3", True),
}


def run_job(name):
    module, enlarged = JOBS[name]
    if enlarged:
        import enlarge_fonts  # noqa: F401  (installs the 8 pt floor before any figure is saved)
    import _common as c
    if module.startswith("supplement_"):
        import generate_canonical_supplement_candidates as g
        for d in (g.SUPP_DIR, g.PNG_DIR, g.DATA_DIR, g.QC_DIR):
            d.mkdir(parents=True, exist_ok=True)
        meta = g.validate_inputs()
        if module == "supplement_s1_s2":
            best = g.load_b100_best()
            g.figure_s1_seed_robustness(best, meta)
            g.figure_s2_composition(best, meta)
        else:
            g.figure_s3_energy_probability_value_alignment(meta)
    else:
        import importlib
        cfg = json.loads((c.OUTPUTS_DIR / "canonical_config.json").read_text(encoding="utf-8"))
        c.validate_protocol_and_hash()
        for m in module.split(","):
            importlib.import_module(m).make_figure(cfg["config_hash"])
    print("OK", name, flush=True)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--job":
        run_job(sys.argv[2])
    else:
        for name in (sys.argv[1:] or list(JOBS)):
            subprocess.run([sys.executable, __file__, "--job", name], check=True)
