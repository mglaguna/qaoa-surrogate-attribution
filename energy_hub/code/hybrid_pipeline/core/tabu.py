"""Structural tabu memory and infeasibility-rule helpers."""

from __future__ import annotations

from hybrid_pipeline.benchmarks.energy_hub.model import structural_filter
from hybrid_pipeline.core.support import _to_bits


class DiscardReason:
    NO_GOOD_EXACT = "no_good_exact"
    STRUCT_RULE = "structural_rule"
    NON_EXACT_K = "non_exact_K"


class StructuralTabu:
    """
    Classical memory layer for candidates generated by any sampler.
    """

    def __init__(self):
        self.visited_exact: set = set()
        self.structural_rules: list = []
        self.rule_labels: list = []
        self.stats = dict(
            no_good_hits=0,
            structural_hits_known=0,
            structural_discoveries=0,
            non_exact_K=0,
            ipopt_avoided_struct=0,
            ipopt_avoided_prescreen=0,
        )

    def register_visit(self, bits: str):
        self.visited_exact.add(bits)

    def add_rule(self, predicate, label: str):
        self.structural_rules.append(predicate)
        self.rule_labels.append(label)
        print(f"  [StructuralTabu] Nueva regla: {label}")

    def classify(self, selection: dict, bits: str, instance: dict) -> tuple:
        ASSETS = instance["ASSETS"]
        K = instance["K"]
        card = sum(selection[i] for i in ASSETS)
        if card != K:
            self.stats["non_exact_K"] += 1
            return True, DiscardReason.NON_EXACT_K, None
        if bits in self.visited_exact:
            self.stats["no_good_hits"] += 1
            return True, DiscardReason.NO_GOOD_EXACT, None
        for pred, label in zip(self.structural_rules, self.rule_labels):
            if pred(selection):
                self.stats["structural_hits_known"] += 1
                self.stats["ipopt_avoided_struct"] += 1
                return True, DiscardReason.STRUCT_RULE, label
        return False, None, None

    def filter_and_classify(self, candidates: list, instance: dict) -> tuple:
        valid, discarded = [], []
        for cand in candidates:
            if isinstance(cand, dict):
                sel = cand["selection"]
                freq = cand.get("freq", 0.0)
                r_score = cand.get("r_score", 0.0)
                risk_score = cand.get("risk_score", 0.0)
                hybrid_score = cand.get("hybrid_score", 0.0)
            else:
                sel, freq, r_score, risk_score, hybrid_score = cand
            bits = _to_bits(sel, instance)
            is_tabu, reason, rule = self.classify(sel, bits, instance)
            if is_tabu:
                discarded.append((sel, freq, reason, rule))
            else:
                valid.append((sel, freq, r_score, risk_score, hybrid_score))
        return valid, discarded

    def n_exact(self):
        return len(self.visited_exact)

    def n_structural(self):
        return len(self.structural_rules)

    def ipopt_avoided_total(self):
        return self.stats["ipopt_avoided_struct"] + self.stats["ipopt_avoided_prescreen"]


def diagnose_infeasibility(selection: dict, instance: dict) -> str:
    """
    Check necessary feasibility conditions without calling IPOPT.
    """
    ASSETS = instance["ASSETS"]
    selected = [i for i in ASSETS if selection[i] == 1]
    if not selected:
        return "empty_selection"

    if instance.get("BENCHMARK") == "energy_hub":
        if not structural_filter(selection, instance):
            return "energy_hub_peak_capacity"
        return "unknown"

    R = instance["R"]
    mu = instance["mu"]
    if max(mu[i] for i in selected) < R:
        return "return_support_ceiling"
    return "unknown"


def infer_and_register_rule(tabu: StructuralTabu, diagnosis: str, instance: dict) -> bool:
    """
    Derive and register a structural rule from an infeasibility diagnosis.
    """
    ASSETS = instance["ASSETS"]
    if diagnosis == "empty_selection":
        tag = "empty_selection"
        if any(tag in lbl for lbl in tabu.rule_labels):
            return False
        tabu.add_rule(
            lambda s, A=ASSETS: sum(s[i] for i in A) == 0,
            "empty_selection",
        )
        return True

    if diagnosis == "energy_hub_peak_capacity":
        tag = "energy_hub_peak_capacity"
        if any(tag in lbl for lbl in tabu.rule_labels):
            return False
        tabu.add_rule(
            lambda s, inst=instance: not structural_filter(s, inst),
            "energy_hub_peak_capacity: soporte sin capacidad agregada pico de calor/frio",
        )
        return True

    R = instance["R"]
    mu = instance["mu"]
    N = instance["N"]
    K = instance["K"]
    N_HIGH = instance["N_HIGH"]
    N_INFEASIBLE_FAMILY = instance["N_INFEASIBLE_FAMILY"]
    INFEASIBLE_SHARE = instance["INFEASIBLE_SHARE"]

    if diagnosis == "return_support_ceiling":
        tag = "return_support_ceiling"
        if any(tag in lbl for lbl in tabu.rule_labels):
            return False
        threshold = R
        rule = lambda s, t=threshold, A=ASSETS, m=mu: (
            sum(s[i] for i in A) > 0
            and max((m[i] for i in A if s[i] == 1), default=0) < t
        )
        tabu.add_rule(
            rule,
            f"return_support_ceiling(R={threshold}): "
            f"excluye C({N-N_HIGH},{K})={N_INFEASIBLE_FAMILY} soportes "
            f"({INFEASIBLE_SHARE:.2%} del espacio de búsqueda)",
        )
        return True

    return False
